// Optimization: Use mem_malloc to support multiple concurrent connections
// and ensure memory is freed in fs_close

struct fs_file *fs_open(const char *name) {
    for (int i = 0; fs_files[i].path != NULL; i++) {
        if (strcmp(name, fs_files[i].path) == 0) {
            struct fs_file *file = (struct fs_file *)mem_malloc(sizeof(struct fs_file));
            if (file == NULL) {
                return NULL;
            }
            file->data = (const char *)fs_files[i].data;
            file->len = fs_files[i].len;
            file->is_open = 1;
            return file;
        }
    }
    return NULL;
}

void fs_close(struct fs_file *file) {
    if (file != NULL) {
        mem_free(file);
    }
}

