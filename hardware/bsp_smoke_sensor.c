float g_smoke_R0 = MQ2_R0_DEFAULT;
uint8_t g_smoke_enabled = 0; // Default Disabled

/**
 * @brief  ??????????????
 */
void SmokeSensor_Init(void)
{
    GPIO_Config_T gpioConfig;

    // 1. ???????
    RCM_EnableAPB2PeriphClock(RCM_APB2_PERIPH_GPIOE | RCM_APB2_PERIPH_GPIOC);

    // 2. ???? D_out (PE0) - ????????
    gpioConfig.pin = SMOKE_DOUT_PIN;
    // gpioConfig.mode = GPIO_MODE_IN_PU;
    gpioConfig.mode = GPIO_MODE_OUT_PP;
    gpioConfig.speed = GPIO_SPEED_50MHz;
    GPIO_Config(SMOKE_DOUT_PORT, &gpioConfig);

    // 3. ???? A_out (PC0) - ???????
    gpioConfig.pin = SMOKE_AOUT_PIN;
    gpioConfig.mode = GPIO_MODE_ANALOG;
    GPIO_Config(SMOKE_AOUT_PORT, &gpioConfig);

    // 4. ???ADC1 ??????????? bsp_adc.c ????????
    // ?????????? GPIO ?????????????

    // 5. ????? RS485 (UART5)
    // RS485_Init();
    
    // ???????????
    memset(&g_smoke_sensor_status, 0, sizeof(SmokeSensor_Status_T));
    
    // Read Flash Config
    Flash_PSU_Config_T config;
    if (Flash_Read_PSU_Config(&config)) {
        // Check if config has smoke_enabled (by checking reserved/new field logic if needed)
        // Since we repurposed reserved[1], old value 0 might mean disabled if not careful.
        // But usually reserved is 0. So if Flash was written before, it might be 0 (Disabled).
        // Let's trust Flash. If user wants to enable, they can click button.
        g_smoke_enabled = config.smoke_enabled;
    } else {
        g_smoke_enabled = 0; // Default OFF if no config
    }

    // printf("[Smoke] Initialized (D_out:PE0, A_out:PC0/ADC1_CH10 via DMA)\n");
}

/**
 * @brief  ???????????????
 */
void SmokeSensor_Update(void)
{
    // static uint32_t last_log_time = 0; // Unused
    extern volatile uint32_t ETHTimer;
    
    if (!g_smoke_enabled) {
        g_smoke_sensor_status.dout_state = 0; // Normal
        g_smoke_sensor_status.aout_voltage = 0.0f;
        g_smoke_sensor_status.smoke_density = 0.0f;
        g_smoke_sensor_status.rs485_status = 0;
        return;
    }

    // ?????? ADC ?????????? (??????)
    g_smoke_sensor_status.adc_raw = ADC_ReadRaw(ADC_CH_SMOKE);
    g_smoke_sensor_status.aout_voltage = ADC_ReadActualVoltage(ADC_CH_SMOKE);
    
    // ?????????? (????????)
    // ????????????????? > 0.1V (????????) ???????? Dout ??
    // ???????? NORMAL (0)????????? Dout ????/??????????
    if (g_smoke_sensor_status.aout_voltage > 0.1f) {
        g_smoke_sensor_status.dout_state = (SmokeSensor_Read_Dout() == SMOKE_STATUS_ALARM) ? 1 : 0;
    } else {
        g_smoke_sensor_status.dout_state = 0; // ??????????????????
    }
    
    // ???? RS485 ??? (????? 1s ???????? 100ms ??????)
    SmokeSensor_RS485_Task();
    
    // ??? RS485 ???? (???) ?? (RS485 ????????? 0 ??????????)????? ADC ????
    // ??: Voltage -> Rs -> Density (????????????)
    if (g_smoke_sensor_status.rs485_status != 0 || 
       (g_smoke_sensor_status.smoke_density < 1.0f && g_smoke_sensor_status.aout_voltage > 0.01f)) {
        
        float v_out = g_smoke_sensor_status.aout_voltage;
        
        // 1. ??????????? (??????????)
        if (v_out > 0.01f && v_out < MQ2_VCC) {
            // 2. ???????????? Rs
            // Rs = ((Vcc - Vout) / Vout) * RL
            float Rs = ((MQ2_VCC - v_out) / v_out) * MQ2_RL;
            
            // 3. ??????? (ppm)
            // ppm = A * (Rs/R0)^(-B)
            float ratio = Rs / g_smoke_R0;
            g_smoke_sensor_status.smoke_density = MQ2_PARAM_A * pow(ratio, -MQ2_PARAM_B);
            
            // ?????????????? (???????????????????)
            if (g_smoke_sensor_status.smoke_density > 10000.0f) {
                g_smoke_sensor_status.smoke_density = 10000.0f;
            }
        } else {
            // ?????????? Vcc?????????????????/????
            g_smoke_sensor_status.smoke_density = 0.0f;
        }
    }
    
    // ?????? 10 ??????? (???? UART ????)
    /*
    if (ETHTimer - last_log_time >= 10000) {
        last_log_time = ETHTimer;
        printf("[Smoke] ADC: %u, V: %.2fV, D: %s, RS485: %s\n", 
               g_smoke_sensor_status.adc_raw, 
               g_smoke_sensor_status.aout_voltage,
               g_smoke_sensor_status.dout_state ? "ALARM" : "NORMAL",
               g_smoke_sensor_status.rs485_status ? "OFFLINE" : "ONLINE");
    }
    */
}

