/**
 * @brief  RS485 ???????
 */
void SmokeSensor_RS485_Task(void)
{
    static uint32_t last_request_time = 0;
    static uint32_t last_response_time = 0;
    extern volatile uint32_t ETHTimer;
    
    // ??????????????
    if (last_response_time == 0) last_response_time = ETHTimer;
    
    // ? 2 ???????????
    if (ETHTimer - last_request_time >= 2000) {
        last_request_time = ETHTimer;
        
        // ?????????
        uint8_t request[] = {0x01, 0x03, 0x00, 0x00, 0x00, 0x01, 0x84, 0x0A};
        RS485_SendData(request, sizeof(request));
    }
    
    // ????????????? 5 ?????????????????????????
    if (ETHTimer - last_response_time > 5000) {
        g_smoke_sensor_status.rs485_status = 1; // Offline
    }
    
    // ???????????????? (?????????)
    if (RS485_GetAvailableData() >= 7) {
        uint8_t response[32];
        uint16_t len = RS485_ReceiveData(response, 32);
        
        if (len >= 7 && response[0] == 0x01 && response[1] == 0x03) {
            uint16_t raw_val = (response[3] << 8) | response[4];
            g_smoke_sensor_status.smoke_density = (float)raw_val / 10.0f;
            g_smoke_sensor_status.rs485_status = 0; // Online
            last_response_time = ETHTimer;          // ?????????????
        }
        // ?????????????????????????????????
        RS485_ClearBuffer();
    }
}
